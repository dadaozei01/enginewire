// Namespace-aware token matching also catches a user parameter's members (User.X.Member), but not User.X2.
bool ContainsUserReference(const FString& Text, const FString& Name)
{
    int32 Start = 0;
    while ((Start = Text.Find(Name, ESearchCase::IgnoreCase, ESearchDir::FromStart, Start)) != INDEX_NONE)
    {
        const int32 End = Start + Name.Len();
        const auto Identifier = [](TCHAR C) { return FChar::IsAlnum(C) || C == TEXT('_'); };
        if ((Start == 0 || (!Identifier(Text[Start - 1]) && Text[Start - 1] != TEXT('.')))
            && (End == Text.Len() || !Identifier(Text[End]))) return true;
        Start = End;
    }
    return false;
}

struct FUserReferenceScan
{
    FString Name;
    TSet<const UNiagaraGraph*> Visited;
    TArray<TSharedPtr<FJsonValue>> References;
    TArray<TSharedPtr<FJsonValue>> Unavailable;

    void Add(const FString& Path, const FString& Kind)
    {
        TSharedPtr<FJsonObject> Ref = MakeShared<FJsonObject>();
        Ref->SetStringField(TEXT("path"), Path);
        Ref->SetStringField(TEXT("kind"), Kind);
        References.Add(MakeShared<FJsonValueObject>(Ref));
    }

    // Reflection is read-only. Includes embedded binding structs and arrays on renderers, DIs and graph nodes;
    // deliberately excludes transient/cache properties and the system's exposed parameter declaration itself.
    void Bindings(UObject* Object)
    {
        for (TFieldIterator<FProperty> It(Object->GetClass()); It; ++It)
        {
            FProperty* Property = *It;
            if (Property->HasAnyPropertyFlags(CPF_Transient | CPF_Deprecated)) continue;
            if (!CastField<FStructProperty>(Property) && !CastField<FArrayProperty>(Property)
                && !CastField<FNameProperty>(Property) && !CastField<FStrProperty>(Property)) continue;
            FString Text;
            Property->ExportText_InContainer(0, Text, Object, Object, Object, PPF_None);
            if (ContainsUserReference(Text, Name)) Add(Object->GetPathName() + TEXT(".") + Property->GetName(), TEXT("reflected_binding_or_hlsl"));
        }
    }

    void Script(UNiagaraScript* Script, const FString& Via)
    {
        if (!Script) return;
        UNiagaraScriptSource* Source = Cast<UNiagaraScriptSource>(Script->GetLatestSource());
        if (!Source || !Source->NodeGraph)
        {
            Unavailable.Add(MakeShared<FJsonValueString>(Via + TEXT(" -> ") + Script->GetPathName()));
            return;
        }
        GraphVisit(Source->NodeGraph, Via);
    }

    void GraphVisit(UNiagaraGraph* Graph, const FString& Via)
    {
        if (!Graph || Visited.Contains(Graph)) return;
        Visited.Add(Graph);
        for (UEdGraphNode* Node : Graph->Nodes)
        {
            if (!Node) continue;
            Bindings(Node);
            for (UEdGraphPin* Pin : Node->Pins)
            {
                if (!Pin) continue;
                if (!ContainsUserReference(Pin->PinName.ToString(), Name)
                    && !ContainsUserReference(Pin->DefaultValue, Name)
                    && !ContainsUserReference(Pin->AutogeneratedDefaultValue, Name)) continue;
                Add(Via + TEXT(" -> ") + Node->GetPathName() + TEXT(".") + Pin->PinName.ToString(), TEXT("graph_pin"));
                // Map Get output -> override Map Set input identifies the exact module.input to the caller.
                for (UEdGraphPin* Link : Pin->LinkedTo) if (Link)
                    Add(Via + TEXT(" -> ") + Link->GetOwningNode()->GetPathName() + TEXT(".") + Link->PinName.ToString(), TEXT("linked_module_input"));
            }
            if (UNiagaraNodeFunctionCall* Call = Cast<UNiagaraNodeFunctionCall>(Node); Call && Call->FunctionScript)
            {
                // Exported getter follows SelectedScriptVersion, not the latest version of an external module.
                UNiagaraScriptSource* Source = Call->GetFunctionScriptSource();
                if (Source && Source->NodeGraph) GraphVisit(Source->NodeGraph, Via + TEXT("/") + Call->GetFunctionName());
                else Unavailable.Add(MakeShared<FJsonValueString>(Via + TEXT("/") + Call->GetFunctionName() + TEXT(": selected script source unavailable")));
            }
        }
    }
};

void SendRemoveError(FActionContext& Context, const FString& Message, const FString& Code)
{
    Context.Result->SetBoolField(TEXT("saved"), false);
    Context.Subsystem->SendAutomationResponse(Context.RequestingSocket, Context.RequestId, false, Message, Context.Result, Code);
}

TSharedPtr<FJsonObject> DIEntries(UNiagaraSystem* System, const FString& RemovedName)
{
    int32 Runtime = 0, Cached = 0, Exposed = 0, Stale = 0;
    for (const FNiagaraVariableWithOffset& Var : System->GetExposedParameters().ReadParameterVariables())
        if (Var.GetType().IsDataInterface()) ++Exposed;
    System->ForEachScriptWithRuntimeData([&](UNiagaraScript*, const FNiagaraScriptRuntimeData* Data)
    {
        for (const FNiagaraScriptResolvedDataInterfaceInfo& Info : Data->GetResolvedDataInterfaces())
        {
            ++Runtime;
            if (ContainsUserReference(Info.Name.ToString(), RemovedName)
                || ContainsUserReference(Info.CompileName.ToString(), RemovedName)
                || Info.ResolvedVariable.GetName() == FName(*RemovedName)
                || Info.ParameterStoreVariable.GetName() == FName(*RemovedName)) ++Stale;
        }
    });
    for (UNiagaraScript* Script : GatherModuleInputScripts(System)) if (Script)
        for (const FNiagaraScriptDataInterfaceInfo& Info : Script->GetCachedDefaultDataInterfaces())
        {
            ++Cached;
            if (ContainsUserReference(Info.Name.ToString(), RemovedName)
                || ContainsUserReference(Info.CompileName.ToString(), RemovedName)
                || Info.RegisteredParameterMapRead == FName(*RemovedName)
                || Info.RegisteredParameterMapWrite == FName(*RemovedName)) ++Stale;
        }
    TSharedPtr<FJsonObject> Result = MakeShared<FJsonObject>();
    Result->SetNumberField(TEXT("exposedDIParameters"), Exposed);
    Result->SetNumberField(TEXT("runtimeDIEntries"), Runtime);
    Result->SetNumberField(TEXT("cachedDIEntries"), Cached);
    Result->SetNumberField(TEXT("removedParameterEntries"), Stale);
    // Inline/module DIs are also compiled; total compiled entries need not equal the exposed DI count.
    return Result;
}

bool HandleUserParameterRemovalAction(FActionContext& Context, const FString& SubAction)
{
    if (SubAction != TEXT("remove_niagara_user_parameter")) return false;
    FString Name = GetJsonStringField(Context.Payload, TEXT("name"));
    Name.RemoveFromStart(TEXT("User."), ESearchCase::IgnoreCase);
    if (Name.IsEmpty() || !ValidateNiagaraIdentifier(Context, Name, TEXT("name"), false))
    {
        if (Name.IsEmpty()) SendRemoveError(Context, TEXT("name must be X or User.X."), TEXT("INVALID_ARGUMENT"));
        return true;
    }
    Name = TEXT("User.") + Name;
    UNiagaraSystem* System = LoadSystemOrError(Context);
    if (!System) return true;
    if (GEditor && GEditor->PlayWorld)
    {
        SendRemoveError(Context, TEXT("Cannot remove user parameters during PIE."), TEXT("PIE_ACTIVE"));
        return true;
    }
    UAssetEditorSubsystem* Editors = GEditor ? GEditor->GetEditorSubsystem<UAssetEditorSubsystem>() : nullptr;
    if (!Editors || Editors->FindEditorForAsset(System, false))
    {
        SendRemoveError(Context, TEXT("Close this system's asset editor first. Nothing was changed."), TEXT("SYSTEM_EDITOR_OPEN"));
        return true;
    }
    TArray<FNiagaraVariable> Parameters;
    System->GetExposedParameters().GetParameters(Parameters);
    const FNiagaraVariable* Found = Parameters.FindByPredicate([&](const FNiagaraVariable& Var) { return Var.GetName() == FName(*Name); });
    if (!Found)
    {
        SendRemoveError(Context, TEXT("User parameter not found: ") + Name, TEXT("PARAM_NOT_FOUND"));
        return true;
    }
    const FNiagaraVariable Parameter = *Found;
    Context.Result->SetStringField(TEXT("parameterName"), Name);
    FUserReferenceScan Scan;
    Scan.Name = Name;
    for (const FNiagaraEmitterHandle& Handle : System->GetEmitterHandles())
    {
        const MCP_NIAGARA_EMITTER_DATA_TYPE* Data = MCP_GET_EMITTER_DATA(Handle);
        if (!Data) Scan.Unavailable.Add(MakeShared<FJsonValueString>(Handle.GetName().ToString() + TEXT(": no inspectable stateful emitter data")));
        else if (Data->SimTarget != ENiagaraSimTarget::CPUSim)
        {
            SendRemoveError(Context, TEXT("Only stateful CPU emitters are supported: GPU shader compilation is not verified. Nothing was changed."), TEXT("NOT_SUPPORTED"));
            return true;
        }
    }
    for (UNiagaraScript* Script : GatherModuleInputScripts(System)) Scan.Script(Script, Script ? Script->GetPathName() : FString());
    TArray<UObject*> Children;
    GetObjectsWithOuter(System, Children, EGetObjectsFlags::IncludeNestedObjects);
    for (UObject* Object : Children)
    {
        // Includes local Scratch scripts and inactive/event/stage graphs, not just the active stack.
        if (UNiagaraGraph* Graph = Cast<UNiagaraGraph>(Object)) Scan.GraphVisit(Graph, Graph->GetPathName());
        if (Object->IsA<UNiagaraDataInterface>() || Object->IsA<UNiagaraRendererProperties>()) Scan.Bindings(Object);
    }
    Context.Result->SetArrayField(TEXT("references"), Scan.References);
    Context.Result->SetArrayField(TEXT("unavailableSources"), Scan.Unavailable);
    if (!Scan.References.IsEmpty())
    {
        SendRemoveError(Context, TEXT("Parameter is still referenced. Delete or rename it manually in the editor. Nothing was changed."), TEXT("PARAMETER_IN_USE"));
        return true;
    }
    if (!Scan.Unavailable.IsEmpty())
    {
        SendRemoveError(Context, TEXT("Some script sources could not be inspected; deletion refused. Nothing was changed."), TEXT("REFERENCE_SCAN_INCOMPLETE"));
        return true;
    }
    if (!GEditor || !GEditor->CanTransact() || GIsTransacting || !GEditor->Trans || GEditor->Trans->IsActive())
    {
        SendRemoveError(Context, TEXT("A separate editor transaction is required. Nothing was changed."), TEXT("TRANSACTION_UNAVAILABLE"));
        return true;
    }
    const TSharedPtr<FJsonObject> Before = DIEntries(System, Name);
    Context.Result->SetObjectField(TEXT("diEntriesBefore"), Before);
    FScopedTransaction Transaction(NSLOCTEXT("EngineWire", "RemoveUnusedNiagaraUserParameter", "Remove unused Niagara user parameter"));
    System->Modify();
    if (UNiagaraDataInterface* DI = Parameter.GetType().IsDataInterface() ? System->GetExposedParameters().GetDataInterface(Parameter) : nullptr) DI->Modify();
    for (UNiagaraScript* Script : GatherModuleInputScripts(System)) if (Script) Script->Modify();
    // Normal virtual dispatch through the exported base interface; do not qualify the base implementation:
    // the engine's UserRedirection override must also remove the bare-name redirection.
    FNiagaraParameterStore& Store = System->GetExposedParameters();
    if (!Store.RemoveParameter(Parameter))
    {
        Transaction.Cancel();
        SendRemoveError(Context, TEXT("Parameter store refused removal. Inspect the asset before retrying."), TEXT("PARAM_REMOVE_FAILED"));
        return true;
    }
    System->RequestCompile(true);
    System->WaitForCompilationComplete(false, false);
    System->MarkPackageDirty();
    TArray<TSharedPtr<FJsonValue>> Warnings, Reports;
    bool CompileOk = true;
    for (UNiagaraScript* Script : GatherModuleInputScripts(System)) if (Script)
    {
        const FNiagaraVMExecutableData& Data = Script->GetVMExecutableData();
        if (Script->GetLastCompileStatus() == ENiagaraScriptCompileStatus::NCS_Error || !Data.ErrorMsg.IsEmpty())
        {
            CompileOk = false;
            Reports.Add(MakeShared<FJsonValueString>(Script->GetPathName() + TEXT(": ") + Data.ErrorMsg));
        }
    }
    TSharedPtr<FJsonObject> After = DIEntries(System, Name);
    const bool Consistent = After->GetNumberField(TEXT("exposedDIParameters")) == Before->GetNumberField(TEXT("exposedDIParameters")) - (Parameter.GetType().IsDataInterface() ? 1 : 0)
        && After->GetNumberField(TEXT("removedParameterEntries")) == 0
        && !System->GetExposedParameters().ReadParameterVariables().ContainsByPredicate([&](const FNiagaraVariableWithOffset& Var) { return Var.GetName() == Parameter.GetName(); });
    if (!Consistent) Warnings.Add(MakeShared<FJsonValueString>(TEXT("Compiled DI entries still refer to the removed parameter or the exposed store still contains it. Not saved; inspect/undo before continuing.")));
    if (!CompileOk) Warnings.Add(MakeShared<FJsonValueString>(TEXT("Compilation failed after removal. Changes remain in memory; use undo. Not saved.")));
    Context.Result->SetObjectField(TEXT("diEntriesAfter"), After);
    Context.Result->SetBoolField(TEXT("diEntriesConsistent"), Consistent);
    Context.Result->SetBoolField(TEXT("compileOk"), CompileOk);
    Context.Result->SetArrayField(TEXT("compiledScripts"), Reports);
    Context.Result->SetArrayField(TEXT("warnings"), Warnings);
    Context.Result->SetBoolField(TEXT("removed"), true);
    Context.Result->SetBoolField(TEXT("saved"), false);
    TSharedPtr<FJsonObject> Undo = MakeShared<FJsonObject>();
    Undo->SetBoolField(TEXT("undoable"), true);
    Undo->SetStringField(TEXT("transactionScope"), TEXT("Niagara user parameter removal"));
    Undo->SetNumberField(TEXT("steps"), 1);
    Context.Result->SetObjectField(TEXT("undo"), Undo);
    Context.SendSuccess(true, TEXT("Unused user parameter removed. Recompiled and marked dirty; not saved."));
    return true;
}

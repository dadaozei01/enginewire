// Equivalent self-member getters are the same value source; original node identities are checked separately.
FString SourceId(const UEdGraphNode* Node)
{
    if (const UK2Node_VariableGet* Getter = Cast<UK2Node_VariableGet>(Node))
    {
        if (Getter->VariableReference.IsSelfContext() && !Getter->VariableReference.IsLocalScope())
        {
            FString Reference;
            FMemberReference::StaticStruct()->ExportText(Reference, &Getter->VariableReference, nullptr, nullptr, PPF_None, nullptr);
            return TEXT("self-get:") + Reference;
        }
    }
    return Node->NodeGuid.ToString();
}
// Ignore reroutes when comparing meaning, but retain every pin type, literal and ultimate value source.
void Endpoints(UEdGraphPin* Pin, TSet<const UEdGraphPin*>& Seen, TArray<FString>& Out)
{
    if (!Pin || Seen.Contains(Pin)) { return; }
    Seen.Add(Pin);
    if (UK2Node_Knot* Knot = Cast<UK2Node_Knot>(Pin->GetOwningNode()))
    {
        for (UEdGraphPin* Next : Knot->GetOutputPin()->LinkedTo) { Endpoints(Next, Seen, Out); }
    }
    else { Out.Add(SourceId(Pin->GetOwningNode()) + TEXT(".") + Pin->PinName.ToString()); }
}
TArray<FString> Meaning(UEdGraph* Graph)
{
    TArray<FString> Rows;
    for (UEdGraphNode* Node : Graph->Nodes)
    {
        if (!Node || Node->IsA<UK2Node_Knot>()) { continue; }
        const FString Id = SourceId(Node);
        Rows.AddUnique(Id + TEXT(":") + Node->GetClass()->GetPathName() + TEXT(":") + Node->NodeComment);
        for (UEdGraphPin* Pin : Node->Pins)
        {
            FString PinType;
            FEdGraphPinType::StaticStruct()->ExportText(PinType, &Pin->PinType, nullptr, nullptr, PPF_None, nullptr);
            Rows.AddUnique(Id + TEXT(".") + Pin->PinName.ToString() + TEXT(":") + PinType + TEXT(":") +
                FString::FromInt(Pin->Direction) + TEXT(":") + Pin->AutogeneratedDefaultValue + TEXT(":") +
                Pin->DefaultValue + TEXT(":") + Pin->DefaultTextValue.ToString() + TEXT(":") + GetPathNameSafe(Pin->DefaultObject));
            if (Pin->Direction == EGPD_Output)
            {
                TSet<const UEdGraphPin*> Seen;
                TArray<FString> Targets;
                for (UEdGraphPin* Target : Pin->LinkedTo) { Endpoints(Target, Seen, Targets); }
                Targets.Sort();
                for (const FString& Target : Targets) { Rows.AddUnique(Id + TEXT(".") + Pin->PinName.ToString() + TEXT("->") + Target); }
            }
        }
    }
    Rows.Sort();
    return Rows;
}

TSharedRef<FJsonObject> Geometry(UEdGraph* Graph, int32& Overlaps)
{
    TSharedRef<FJsonObject> Result = MakeShared<FJsonObject>();
    TArray<TSharedPtr<FJsonValue>> Items;
    TArray<FBox2D> Boxes;
    for (UEdGraphNode* Node : Graph->Nodes)
    {
        if (!Node || Node->IsA<UEdGraphNode_Comment>()) { continue; }
        const McpRuled::FShape Shape = McpRuled::EstimateShape(*Node);
        TSharedRef<FJsonObject> Item = MakeShared<FJsonObject>();
        Item->SetStringField(TEXT("id"), Node->NodeGuid.ToString());
        Item->SetStringField(TEXT("title"), Node->GetNodeTitle(ENodeTitleType::ListView).ToString());
        Item->SetNumberField(TEXT("x"), Node->NodePosX);
        Item->SetNumberField(TEXT("y"), Node->NodePosY);
        Item->SetNumberField(TEXT("width"), Shape.Width);
        Item->SetNumberField(TEXT("height"), Shape.Height);
        Item->SetNumberField(TEXT("execIn"), Shape.ExecIn);
        Items.Add(MakeShared<FJsonValueObject>(Item));
        const FBox2D Box(FVector2D(Node->NodePosX, Node->NodePosY), FVector2D(Node->NodePosX + Shape.Width, Node->NodePosY + Shape.Height));
        for (const FBox2D& Other : Boxes)
        {
            if (Box.Min.X < Other.Max.X && Other.Min.X < Box.Max.X && Box.Min.Y < Other.Max.Y && Other.Min.Y < Box.Max.Y) { ++Overlaps; }
        }
        Boxes.Add(Box);
    }
    Result->SetArrayField(TEXT("nodes"), Items);
    Result->SetNumberField(TEXT("overlaps"), Overlaps);
    return Result;
}

bool Render(UEdGraph* Graph, const FString& Path)
{
    if (!FApp::CanEverRender() || GUsingNullRHI) { return false; }
    FBox2D Bounds(ForceInit);
    for (UEdGraphNode* Node : Graph->Nodes)
    {
        if (!Node || Node->IsA<UEdGraphNode_Comment>()) { continue; }
        const McpRuled::FShape Shape = McpRuled::EstimateShape(*Node);
        Bounds += FVector2D(Node->NodePosX, Node->NodePosY);
        Bounds += FVector2D(Node->NodePosX + Shape.Width, Node->NodePosY + Shape.Height);
    }
    if (!Bounds.bIsValid) { return false; }
    const FVector2D Size(FMath::Min(4096.0, Bounds.GetSize().X + 128.0),
                         FMath::Min(2304.0, Bounds.GetSize().Y + 128.0));
    const float Zoom = FMath::Min(1.0, FMath::Min((Size.X - 128.0) / Bounds.GetSize().X, (Size.Y - 128.0) / Bounds.GetSize().Y));
    TSharedRef<SGraphEditor> Editor = SNew(SGraphEditor).GraphToEdit(Graph).IsEditable(false);
    Editor->GetGraphPanel()->Update();
    Editor->SetViewLocation(FVector2D(Bounds.Min - FVector2D(64.0 / Zoom, 64.0 / Zoom)), Zoom);
    FWidgetRenderer Renderer(true, true);
    UTextureRenderTarget2D* Target = Renderer.DrawWidget(Editor, Size);
    if (!Target) { return false; }
    FlushRenderingCommands();
    TArray<FColor> Pixels;
    if (!Target->GameThread_GetRenderTargetResource()->ReadPixels(Pixels)) { return false; }
    TArray<uint8> Png;
    FImageUtils::CompressImageArray(static_cast<int32>(Size.X), static_cast<int32>(Size.Y), Pixels, Png);
    return FFileHelper::SaveArrayToFile(Png, *Path);
}
